// Outlines the wordmark's letters into src/brand/wordmark-path.ts, so the logo looks the same
// without the font loaded. Run only when the wordmark's type changes:
//   npm run wordmark
import { writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { Resvg } from '@resvg/resvg-js'
import { brandFont } from './fonts.mjs'

const out = join(dirname(fileURLToPath(import.meta.url)), '..', 'src', 'brand', 'wordmark-path.ts')

// Big Shoulders Display 800, capitals, tracked 0.05em: the board's approved lockup.
const FONT_SIZE = 100
const TRACKING = 5
const svg =
  `<svg xmlns="http://www.w3.org/2000/svg" width="900" height="300">` +
  `<text x="0" y="200" font-family="Big Shoulders Display" font-weight="800" font-size="${FONT_SIZE}" letter-spacing="${TRACKING}">UMBRISTA</text></svg>`
const resvg = new Resvg(svg, {
  font: { fontFiles: [brandFont('big-shoulders-display', 800)], loadSystemFonts: false },
})

// resvg's toString() returns the normalised SVG, in which text has become paths.
const paths = [...resvg.toString().matchAll(/ d="([^"]+)"/g)].map((m) => m[1])
if (paths.length === 0) throw new Error('no outlines produced: is Big Shoulders Display 800 loaded?')

const round = (n) => String(Math.round(Number(n) * 100) / 100)
const d = paths
  .join(' ')
  .replace(/-?\d+(\.\d+)?/g, round)
  .replace(/\s*([MLQCZ])\s*/g, '$1')
  .trim()

// The tight box around the outlines, from the renderer, so the drawing can be cropped to it.
const box = resvg.innerBBox() ?? resvg.getBBox()
if (!box) throw new Error('no bounding box for the wordmark')
const b = [box.x, box.y, box.width, box.height].map(round).join(', ')

writeFileSync(
  out,
  `// Generated by scripts/outline-wordmark.mjs from Big Shoulders Display 800. Do not edit by hand.\n` +
    `// "UMBRISTA" at font-size ${FONT_SIZE}, letter-spacing ${TRACKING}, from x 0 with the baseline at y 200.\n` +
    `export const WORDMARK_PATH =\n  '${d}'\n\n` +
    `/** [x, y, width, height] of the outlines in the path's own coordinates. */\n` +
    `export const WORDMARK_BOX = [${b}] as const\n`,
)
console.log(`wrote ${out} (${d.length} characters, box ${b})`)
